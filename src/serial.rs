//! # シリアルポート制御モジュール
//!
//! ## シリアルポートとは何か？
//!
//! シリアルポートは**「データを1ビットずつ順番に送る通信ハードウェア」**です。
//! 単なる設定ではなく、実際にデータの送受信を行う物理的なハードウェアです。
//!
//! ### 物理的な構造
//! ```
//! ┌─────────────────────────────────────┐
//! │           コンピュータ内部             │
//! │  ┌─────────┐    ┌─────────────────┐ │
//! │  │   CPU   │◄──►│ シリアルポート    │──┼──► 外部デバイス
//! │  │         │    │   ハードウェア    │ │    (モデム、端末等)
//! │  └─────────┘    └─────────────────┘ │
//! └─────────────────────────────────────┘
//! ```
//!
//! ### シリアル通信の仕組み
//! ```
//! パラレル通信（昔のプリンタなど）：
//! データ: 01001010
//! 送信:   ||||||||  ← 8本の線で同時に送信
//!        01001010
//!
//! シリアル通信：
//! データ: 01001010
//! 送信:   0→1→0→0→1→0→1→0  ← 1本の線で順番に送信
//! ```
//!
//! ### ハードウェアの主要構成要素
//! - **送信バッファ**: 送信待ちのデータを一時保存
//! - **受信バッファ**: 受信したデータを一時保存
//! - **シフトレジスタ**: データを1ビットずつ送受信
//! - **ボーレートジェネレータ**: 正確なタイミング制御
//! - **制御レジスタ**: 通信設定を管理
//!
//! ### 文字送信の実際の流れ（例：'A' = 01000001）
//! ```
//! 時間軸 →
//!      ┌─┐   ┌───┐       ┌─┐
//! ─────┘ └───┘   └───────┘ └─────
//!      S 0 1 0 0 0 0 0 1 E
//!
//! S = スタートビット（通信開始の合図）
//! 01000001 = データビット（'A'の文字コード）
//! E = ストップビット（通信終了の合図）
//! ```
//!
//! ## OS開発におけるシリアルポートの重要性
//!
//! OS開発では「鶏と卵」問題が発生します：
//! - OSを作っている → まだ画面出力機能がない → デバッグできない → OSが作れない
//!
//! シリアルポートはこの問題を解決する「最後の砦」として機能します：
//!
//! ### 1. ハードウェアレベルでの独立性
//! - CPUと直接接続された非常にシンプルなハードウェア
//! - グラフィックカード、メモリ管理、ファイルシステムと完全に独立
//! - 複雑なドライバが不要
//!
//! ### 2. 最小限の初期化で動作
//! - I/Oポートへの数回の書き込みのみで動作開始
//! - メモリ割り当て不要、複雑な設定不要
//! - CPU起動直後から使用可能
//!
//! ### 3. 確実な出力保証
//! - 同期通信による確実なデータ送信
//! - バッファリングが最小限
//! - 送信完了を確認してから次のデータを送信
//!
//! ### 4. 外部システムとの連携
//!
//! シリアルポートの最大の利点は、**開発中のOSと外部システムを繋ぐ橋渡し**をすることです。
//!
//! #### 仮想マシン環境での連携（QEMU）
//! ```bash
//! # シリアル出力をファイルに保存
//! qemu-system-x86_64 -serial file:debug.log your_os.img
//!
//! # シリアル出力をホストOSの端末に表示
//! qemu-system-x86_64 -serial stdio your_os.img
//!
//! # シリアル出力をTCPポートに転送（リモート監視）
//! qemu-system-x86_64 -serial tcp:localhost:1234,server your_os.img
//! ```
//!
//! **動作の仕組み：**
//! ```
//! ┌─────────────────────────────────────────────────────────────┐
//! │                あなたの開発マシン（ホストOS）                    │
//! │  ┌─────────────────┐    ┌─────────────────────────────────┐ │
//! │  │   ターミナル1     │    │           QEMU仮想マシン          │ │
//! │  │                 │    │  ┌─────────────────────────────┐ │ │
//! │  │ $ tail -f       │◄───┤  │     開発中のOS（wasabi）      │ │ │
//! │  │   debug.log     │    │  │                             │ │ │
//! │  │                 │    │  │ serial.send_str("Hello");   │ │ │
//! │  └─────────────────┘    │  │           ↓                 │ │ │
//! │                         │  │    シリアルポート(0x3F8)      │ │  │
//! │  ┌─────────────────┐    │  └─────────────────────────────┘│  │
//! │  │   ターミナル2     │    │              ↓                  │  │
//! │  │                 │    │        QEMUが検出・転送           │  │
//! │  │ $ qemu-system-  │    │              ↓                  │  │
//! │  │   x86_64 -serial│    │        debug.logファイルに保存    │  │
//! │  │   file:debug.log│    └─────────────────────────────────┘ │
//! │  └─────────────────┘                                        │
//! └─────────────────────────────────────────────────────────────┘
//! ```
//!
//! **具体的な流れ：**
//! 1. **開発中のOS（wasabi）**がシリアルポート（0x3F8）に「Hello」を書き込み
//! 2. **QEMU**がその書き込みを仮想ハードウェアとして検出
//! 3. **QEMU**が「Hello」をホストOSの`debug.log`ファイルに転送・保存
//! 4. **あなた**がホストOSの別ターミナルで`tail -f debug.log`でリアルタイム監視
//!
//! つまり、**同じマシン上で2つのOS**が動いています：
//! - **ホストOS**：あなたが普段使っているOS（macOS/Linux/Windows）
//! - **ゲストOS**：QEMUの中で動く開発中のOS（wasabi）
//!
//! #### 物理マシンでの連携
//! ```
//! [開発マシン] ←→ [シリアルケーブル] ←→ [ターゲットマシン（開発中のOS）]
//!      ↑                                           ↑
//!   端末ソフト                                シリアルポート出力
//!  (minicom等)
//! ```
//!
//! #### 実際の開発ワークフロー例
//! ```bash
//! # ターミナル1: OSをQEMUで起動
//! qemu-system-x86_64 -serial file:debug.log wasabi.img
//!
//! # ターミナル2: リアルタイムでログ監視
//! tail -f debug.log
//!
//! # ターミナル3: ログ解析
//! grep "ERROR" debug.log
//! grep "Memory initialized" debug.log
//! ```
//!
//! #### 高度な連携例
//! - **自動テスト**: シリアル出力を解析して成功/失敗を判定
//! - **パフォーマンス測定**: タイムスタンプ付きログで処理時間を測定
//! - **リモートデバッグ**: ネットワーク経由でシリアル出力を監視
//! - **CI/CD統合**: ビルドサーバーでのOS動作確認
//!
//! ## 使用例
//!
//! ### 起動直後のデバッグ
//! ```rust
//! fn early_boot() {
//!     let mut serial = SerialPort::new_for_com1();
//!     serial.init();
//!     serial.send_str("Boot started!\n");  // 外部に出力される
//!
//!     init_memory();
//!     serial.send_str("Memory initialized\n");
//!     // クラッシュしても、どこまで進んだかわかる
//! }
//! ```
//!
//! ### パニック時の情報保存
//! ```rust
//! #[panic_handler]
//! fn panic(info: &PanicInfo) -> ! {
//!     let mut serial = SerialPort::new_for_com1();
//!     serial.send_str("PANIC: ");
//!     serial.send_str(&format!("{}", info));  // 画面が真っ黒でも外部に送信
//!     loop {}
//! }
//! ```
//!
//! ### QEMUでの使用
//! ```bash
//! # シリアル出力をファイルに保存
//! qemu-system-x86_64 -serial file:debug.log
//! ```
//!
//! ## 技術仕様
//! - 対象：RS-232C準拠シリアルポート
//! - 標準設定：115200bps, 8N1（8ビット、パリティなし、ストップビット1）
//! - COM1ポート：I/Oベースアドレス 0x3F8
//!
//! 参考：https://wiki.osdev.org/Serial_Ports

use crate::x86::busy_loop_hint;
use crate::x86::read_io_port_u8;
use crate::x86::write_io_port_u8;
use core::fmt;

/// シリアルポート制御構造体
///
/// ## 設計思想
/// - 最小限のフィールドで最大限の機能を提供
/// - ハードウェアレジスタへの直接アクセスによる高速動作
/// - エラー処理よりも確実性を重視した設計
///
/// ## I/Oポートレイアウト（COM1の場合：base = 0x3F8）
/// - base + 0: データレジスタ（送受信）/ ボーレート下位バイト（DLAB=1時）
/// - base + 1: 割り込み有効レジスタ / ボーレート上位バイト（DLAB=1時）
/// - base + 2: 割り込み識別・FIFO制御レジスタ
/// - base + 3: ライン制御レジスタ（データフォーマット、DLAB制御）
/// - base + 4: モデム制御レジスタ（RTS、DTR制御）
/// - base + 5: ライン状態レジスタ（送信準備完了、エラー状態）
/// - base + 6: モデム状態レジスタ
/// - base + 7: スクラッチレジスタ
pub struct SerialPort {
    /// シリアルポートのベースI/Oアドレス
    ///
    /// 標準的なCOMポートアドレス：
    /// - COM1: 0x3F8
    /// - COM2: 0x2F8
    /// - COM3: 0x3E8
    /// - COM4: 0x2E8
    base: u16,
}

impl SerialPort {
    /// 指定されたベースアドレスでシリアルポートインスタンスを作成
    ///
    /// # パラメータ
    /// - `base`: シリアルポートのベースI/Oアドレス
    ///
    /// # 注意
    /// この時点では初期化は行われません。使用前に`init()`を呼び出してください。
    pub fn new(base: u16) -> Self {
        Self { base }
    }

    /// COM1ポート用のシリアルポートインスタンスを作成
    ///
    /// COM1は最も一般的に使用されるシリアルポートで、
    /// ほぼすべてのx86システムでサポートされています。
    ///
    /// # COM1の特徴
    /// - I/Oベースアドレス: 0x3F8
    /// - IRQ: 4
    /// - 最も安定した動作が期待できる
    /// - QEMUなどのエミュレータで標準サポート
    pub fn new_for_com1() -> Self {
        // COM1のI/Oポートアドレス 0x3F8を使用
        Self::new(0x3f8)
    }

    /// シリアルポートを初期化
    ///
    /// ## 初期化手順の詳細
    ///
    /// シリアルポートの初期化は、ハードウェアレジスタを正しい順序で
    /// 設定することで行われます。各ステップには技術的な理由があります。
    ///
    /// ## 設定される通信パラメータ
    /// - **ボーレート**: 115200bps（高速通信）
    /// - **データビット**: 8ビット
    /// - **パリティ**: なし
    /// - **ストップビット**: 1ビット
    /// - **フロー制御**: ハードウェアフロー制御有効
    ///
    /// ## 初期化が必要な理由
    /// - ハードウェアリセット後の状態は不定
    /// - BIOS/UEFIによる設定が残っている可能性
    /// - 確実な動作のために既知の状態に設定
    ///
    /// # パニック
    /// この関数はパニックしません。I/O操作が失敗してもシステムは継続動作します。
    pub fn init(&mut self) {
        // ステップ1: 全ての割り込みを無効化
        // 理由: 初期化中に予期しない割り込みを防ぐ
        // レジスタ: IER (Interrupt Enable Register) = base + 1
        // 値: 0x00 = すべての割り込みソースを無効
        write_io_port_u8(self.base + 1, 0x00);

        // ステップ2: DLAB（Data Latch Access Bit）を有効にしてボーレート設定モードに
        // 理由: ボーレート設定レジスタにアクセスするため
        // レジスタ: LCR (Line Control Register) = base + 3
        // 値: 0x80 = DLAB=1, 他のビットは0
        write_io_port_u8(self.base + 3, 0x80);

        // ステップ3: ボーレート除数を設定
        // 計算式: ボーレート = 115200 / BAUD_DIVISOR
        // 115200bps設定のため BAUD_DIVISOR = 1
        // 除数は16ビット値なので上位・下位バイトに分けて設定
        const BAUD_DIVISOR: u16 = 0x0001;
        write_io_port_u8(self.base, (BAUD_DIVISOR & 0xff) as u8);        // 下位バイト
        write_io_port_u8(self.base + 1, (BAUD_DIVISOR >> 8) as u8);      // 上位バイト

        // ステップ4: データフォーマットを設定し、DLABを無効化
        // レジスタ: LCR (Line Control Register) = base + 3
        // 値: 0x03 = 8ビット(bit1-0=11), パリティなし(bit3=0), ストップビット1(bit2=0), DLAB=0(bit7=0)
        // ビット構成: 0000 0011
        //           ||||  ||||
        //           ||||  ||++-- データビット長: 11=8ビット
        //           ||||  |+---- ストップビット: 0=1ビット
        //           ||||  +----- パリティ有効: 0=無効
        //           ||++-------- パリティ種別: 00=奇数（無効なので無関係）
        //           |+---------- ブレーク制御: 0=無効
        //           +----------- DLAB: 0=通常モード
        write_io_port_u8(self.base + 3, 0x03);

        // ステップ5: FIFO制御を設定
        //
        // ## FIFOとは？
        // FIFO = First In, First Out（先入れ先出し）のバッファ
        // シリアル通信では、データの送受信を効率化するためのバッファシステム
        //
        // ## FIFO無しの場合の問題：
        // - 1文字ずつしか処理できない
        // - CPUが常にシリアルポートを監視する必要がある
        // - 高速通信時にデータ損失のリスク
        //
        // ## FIFOありの場合の利点：
        // - 最大16文字まで一度にバッファリング可能
        // - CPUの負荷を軽減
        // - 連続データ送信時の効率向上
        // - データ損失リスクの大幅削減
        //
        // ## 具体例：
        // FIFO無し: [C][P][U] ←→ [1文字] ←→ [シリアル回線]
        // FIFO有り: [C][P][U] ←→ [16文字バッファ] ←→ [シリアル回線]
        //
        // レジスタ: FCR (FIFO Control Register) = base + 2
        // 値: 0xC7 = FIFO有効、送受信FIFOクリア、14バイト閾値
        // ビット構成: 1100 0111
        //           |||| ||||
        //           |||| |||+-- FIFO有効: 1=有効
        //           |||| ||+--- 受信FIFOクリア: 1=クリア（初期化時にバッファをクリア）
        //           |||| |+---- 送信FIFOクリア: 1=クリア（初期化時にバッファをクリア）
        //           |||| +----- DMAモード: 0=無効（Direct Memory Accessは使わない）
        //           ||++------- 予約ビット: 00
        //           ++--------- 受信FIFO閾値: 11=14バイト（14文字溜まったら割り込み）
        write_io_port_u8(self.base + 2, 0xc7);

        // ステップ6: モデム制御信号を設定
        //
        // ## モデム制御とは？
        // モデム制御信号は、シリアル通信における「握手」のためのハードウェア信号
        // 昔のモデム（電話回線でデータ通信する装置）との互換性のために存在
        // 現代では主にフロー制御（データの流量制御）に使用
        //
        // ## 主要な制御信号：
        //
        // ### DTR (Data Terminal Ready)
        // - 意味：「こちら（端末）は通信準備完了です」
        // - 用途：相手に自分が動作中であることを伝える
        // - 例：PCが「私は起動していて、通信可能です」と宣言
        //
        // ### RTS (Request To Send)
        // - 意味：「データを送信したいです」
        // - 用途：送信許可を相手に要求
        // - フロー制御：相手が忙しい時は送信を待つ
        //
        // ### CTS (Clear To Send) - 相手からの信号
        // - 意味：「送信してもOKです」
        // - 用途：RTSに対する応答
        // - フロー制御：この信号がONの時だけ送信可能
        //
        // ### DSR (Data Set Ready) - 相手からの信号
        // - 意味：「相手（モデム）は準備完了です」
        // - 用途：相手が動作中であることを確認
        //
        // ## 現代での使用例：
        // ```
        // [PC] ←→ [シリアルケーブル] ←→ [組み込み機器]
        //  ↑                              ↑
        // DTR=1                         DSR=1
        // RTS=1 ←→ フロー制御 ←→ CTS=1
        // "準備OK"                    "送信OK"
        // ```
        //
        // ## OS開発での重要性：
        // - QEMUなどのエミュレータが正常な通信を認識
        // - 物理マシンでの実際のシリアル通信で必要
        // - 信号が正しく設定されていないと通信が失敗する場合がある
        //
        // レジスタ: MCR (Modem Control Register) = base + 4
        // 値: 0x0B = 割り込み有効、RTS/DTR有効
        // ビット構成: 0000 1011
        //           |||| ||||
        //           |||| |||+-- DTR (Data Terminal Ready): 1=アクティブ
        //           |||| ||+--- RTS (Request To Send): 1=アクティブ
        //           |||| |+---- Out1: 1=アクティブ（汎用出力信号）
        //           |||| +----- Out2 (割り込み有効): 1=アクティブ（割り込み制御）
        //           |||+------- ループバックモード: 0=無効（テスト用機能）
        //           +++-------- 予約ビット: 000
        write_io_port_u8(self.base + 4, 0x0B);
    }
    /// 1文字をシリアルポートに送信
    ///
    /// ## 動作原理
    ///
    /// シリアル通信は**同期通信**です。送信バッファが空になるまで
    /// 待機してから次の文字を送信する必要があります。
    ///
    /// ## 送信手順
    /// 1. **送信準備完了チェック**: LSR（Line Status Register）のbit 5を監視
    /// 2. **ビジーウェイト**: 送信バッファが空になるまで待機
    /// 3. **データ送信**: データレジスタに文字を書き込み
    ///
    /// ## LSR（Line Status Register）bit 5の意味
    /// - **1**: 送信ホールドレジスタが空（送信可能）
    /// - **0**: まだ前の文字を送信中（待機が必要）
    ///
    /// ## パフォーマンス最適化
    /// - `busy_loop_hint()`でCPUに最適化ヒントを提供
    /// - スピンロック中の電力消費を削減
    /// - マルチスレッド環境での効率化
    ///
    /// # パラメータ
    /// - `c`: 送信する文字（Unicode文字をUTF-8の最初のバイトとして送信）
    ///
    /// # 注意
    /// - 非ASCII文字は正しく表示されない可能性があります
    /// - この関数はブロッキング動作します（送信完了まで戻りません）
    /// - 初期化前に呼び出すと不定の動作をします
    pub fn send_char(&self, c: char) {
        // 送信準備完了まで待機
        // LSR (Line Status Register) = base + 5
        // bit 5 = THRE (Transmitter Holding Register Empty)
        // 0x20 = 0010 0000 (bit 5のマスク)
        while (read_io_port_u8(self.base + 5) & 0x20) == 0 {
            // CPUに最適化ヒントを提供（PAUSE命令）
            // - スピンロック中の電力消費を削減
            // - 他のハイパースレッドに実行機会を提供
            // - パイプラインの最適化
            busy_loop_hint();
        }

        // データレジスタ（base + 0）に文字を書き込み
        // char -> u8 変換：Unicode文字の最初のバイトを送信
        // 注意：非ASCII文字は正しく表示されない可能性
        write_io_port_u8(self.base, c as u8)
    }

    /// 文字列をシリアルポートに送信
    ///
    /// ## 動作原理
    ///
    /// 文字列を1文字ずつ順次送信します。各文字の送信完了を
    /// 確認してから次の文字を送信するため、確実な送信が保証されます。
    ///
    /// ## 実装の特徴
    /// - **確実性重視**: 各文字の送信完了を確認
    /// - **シンプル設計**: エラー処理よりも動作の確実性を優先
    /// - **ブロッキング動作**: 全文字の送信完了まで戻らない
    ///
    /// ## パフォーマンス考慮事項
    /// - 長い文字列の送信には時間がかかります
    /// - 115200bpsでも1文字あたり約87μs必要
    /// - 1000文字の送信には約87ms必要
    ///
    /// # パラメータ
    /// - `s`: 送信する文字列（UTF-8エンコード）
    ///
    /// # 使用例
    /// ```rust
    /// let mut serial = SerialPort::new_for_com1();
    /// serial.init();
    /// serial.send_str("Hello, World!\n");
    /// serial.send_str("Debug: value = 42\n");
    /// ```
    ///
    /// # 注意
    /// - 日本語などの非ASCII文字は正しく表示されません
    /// - 改行文字（\n）は適切に処理されます
    /// - 初期化前に呼び出すと不定の動作をします
    pub fn send_str(&self, s: &str) {
        // 文字列を文字単位で反復処理
        // chars()でUnicode文字境界を正しく認識
        let mut sc = s.chars();
        let slen = s.chars().count();

        // 各文字を順次送信
        // 注意：chars().count()は文字列を2回走査するため非効率
        // しかし、確実性とシンプルさを優先
        for _ in 0..slen {
            // unwrap()使用：文字数をカウント済みなので安全
            self.send_char(sc.next().unwrap());
        }
    }
}

/// Rustの標準フォーマット機能との統合
///
/// ## fmt::Writeトレイトの実装
///
/// このトレイト実装により、`write!`や`writeln!`マクロが使用可能になります。
/// これにより、フォーマット文字列を使った便利な出力が可能です。
///
/// ## 使用例
/// ```rust
/// use core::fmt::Write;
///
/// let mut serial = SerialPort::new_for_com1();
/// serial.init();
///
/// // フォーマット文字列を使用した出力
/// write!(serial, "Value: {}\n", 42).unwrap();
/// writeln!(serial, "Debug: x={}, y={}", x, y).unwrap();
///
/// // 複雑なフォーマット
/// writeln!(serial, "Hex: 0x{:08X}, Binary: {:08b}", value, value).unwrap();
/// ```
///
/// ## 実装の注意点
/// - 内部で新しいSerialPortインスタンスを作成（設計上の制約）
/// - エラーは常にOk(())を返す（シンプルさを優先）
/// - パフォーマンスよりも使いやすさを重視
impl fmt::Write for SerialPort {
    /// 文字列をシリアルポートに書き込み
    ///
    /// # パラメータ
    /// - `s`: 書き込む文字列
    ///
    /// # 戻り値
    /// 常に`Ok(())`を返します（エラー処理は行いません）
    ///
    /// # 注意
    /// この実装では新しいSerialPortインスタンスを作成するため、
    /// 初期化状態は引き継がれません。実用的には問題ありませんが、
    /// 設計上の制約として理解しておいてください。
    fn write_str(&mut self, s: &str) -> fmt::Result {
        let serial = Self::default();
        serial.send_str(s);
        Ok(())
    }
}

/// デフォルト実装
///
/// ## Defaultトレイトの実装
///
/// SerialPortのデフォルトインスタンスとしてCOM1ポートを提供します。
/// これにより、明示的な設定なしで最も一般的な設定を使用できます。
///
/// ## 使用例
/// ```rust
/// // 以下の2つは同等
/// let serial1 = SerialPort::default();
/// let serial2 = SerialPort::new_for_com1();
///
/// // デフォルト値を使用した初期化
/// let mut serial = SerialPort::default();
/// serial.init();
/// serial.send_str("Hello from default port!\n");
/// ```
///
/// ## 設計思想
/// - **最も一般的な設定をデフォルトに**: COM1は最も広くサポートされている
/// - **簡単な使用開始**: 複雑な設定なしで即座に使用可能
/// - **標準的なRustパターン**: Defaultトレイトの慣用的な使用
impl Default for SerialPort {
    /// COM1ポート用のデフォルトインスタンスを作成
    ///
    /// # 戻り値
    /// COM1ポート（0x3F8）に設定されたSerialPortインスタンス
    ///
    /// # 注意
    /// 初期化は行われません。使用前に`init()`を呼び出してください。
    fn default() -> Self {
        Self::new_for_com1()
    }
}
